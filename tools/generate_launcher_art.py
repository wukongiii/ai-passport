#!/usr/bin/env python3
"""Generate original geometric launcher illustrations and Flash RGB565 assets.
Requires Pillow; run with PYTHONPATH=build/art-tools python3 tools/generate_launcher_art.py.
"""
from pathlib import Path
import argparse
import math
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'assets/images/launcher'
OUT.mkdir(parents=True, exist_ok=True)
W, H, S = 176, 96, 3
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--font', required=True, help='Noto Sans CJK SC source used by the scoreboard')
args = parser.parse_args()
FONT = ImageFont.truetype(args.font, 23*S)
SMALL = ImageFont.truetype(args.font, 10*S)

def ball(im, x, y, r, color, number=None):
    d=ImageDraw.Draw(im)
    x,y,r=[int(v*S) for v in (x,y,r)]
    d.ellipse((x-r+2*S,y-r+5*S,x+r+2*S,y+r+5*S),fill='#071b22')
    c=tuple(int(color[i:i+2],16) for i in (1,3,5))
    for rr in range(r,0,-1):
        t=1-rr/r
        shade=tuple(min(255,int(v*(.65+.35*t))) for v in c)
        d.ellipse((x-rr,y-rr,x+rr,y+rr),fill=shade)
    d.ellipse((x-r*.55,y-r*.65,x-r*.12,y-r*.32),fill=tuple(min(255,int(v*.35+165)) for v in c))
    if number:
        rad=r*.45
        d.ellipse((x-rad,y-rad,x+rad,y+rad),fill='#f8f3df')
        font=FONT if r>20*S else SMALL
        d.text((x,y),str(number),font=font,anchor='mm',fill='#15232b')

def image(kind):
    im=Image.new('RGB',(W*S,H*S)); d=ImageDraw.Draw(im)
    themes=[(12,65,61),(23,48,74),(57,29,47),(23,42,65),(29,33,75)]
    base=themes[kind]
    for y in range(H*S):
        a=y/(H*S)
        c=tuple(int(v*(1-.45*a)) for v in base)
        d.line((0,y,W*S,y),fill=c)
    def line(points,fill,width=1):
        d.line([(int(x*S),int(y*S)) for x,y in points],fill=fill,width=width*S)
    for x in range(-96,250,24): line([(x,96),(x+96,0)],'#28424a')
    d.rounded_rectangle((7*S,6*S,169*S,90*S),radius=12*S,outline='#45656a',width=S)
    if kind==0:
        line([(15,84),(154,12)],'#d2af76',3)
        line([(16,84),(37,73)],'#f0dfb5',2)
        ball(im,118,39,29,'#202c36',8); ball(im,62,62,20,'#fbf6dd')
    elif kind==1:
        line([(18,82),(157,14)],'#d2af76',2)
        for x,y,r,c,n in [(47,50,23,'#e4ba49',1),(88,60,24,'#6985be',4),(129,44,24,'#cb644f',7)]:
            ball(im,x,y,r,c,n)
    elif kind==2:
        for x,y in [(70,31),(94,31),(58,52),(82,52),(106,52)]: ball(im,x,y,12,'#dc4d56')
        ball(im,128,66,20,'#202c36'); ball(im,43,73,15,'#fbf6dd')
    elif kind==3:
        cx,cy=88*S,48*S
        for angle in range(0,360,45):
            a=math.radians(angle)
            x,y=cx+28*S*math.cos(a),cy+28*S*math.sin(a)
            d.rounded_rectangle((x-7*S,y-7*S,x+7*S,y+7*S),radius=3*S,fill='#92b9c3')
        d.ellipse((cx-29*S,cy-29*S,cx+29*S,cy+29*S),fill='#83b0bc')
        d.ellipse((cx-17*S,cy-17*S,cx+17*S,cy+17*S),fill='#19354a')
        d.ellipse((cx-8*S,cy-8*S,cx+8*S,cy+8*S),fill='#e5d29c')
    else:
        for i,height in enumerate([13,24,35,25,16,31,41,23,13]):
            x=(32+i*14)*S
            d.rounded_rectangle((x,48*S-height*S/2,x+5*S,48*S+height*S/2),radius=2*S,fill='#7dbdcc' if i%2 else '#c1a4e3')
        d.ellipse((142*S,14*S,146*S,18*S),fill='#f5d995')
        line([(144,10),(144,22)],'#f5d995');line([(138,16),(150,16)],'#f5d995')
    return im.resize((W,H),Image.Resampling.LANCZOS)

names=['eight','chase','snooker','settings','voice']
parts=['/* Generated by tools/generate_launcher_art.py; original project artwork. */\n#include "lvgl.h"\n']
for kind,name in enumerate(names):
    im=image(kind);im.save(OUT/f'{name}.png')
    data=[]
    for r,g,b in list(im.convert("RGB").get_flattened_data()):
        v=((r>>3)<<11)|((g>>2)<<5)|(b>>3)
        data.extend([v&255,v>>8])
    parts.append(f'static const uint8_t pixels_{name}[] = {{\n')
    parts.extend('    '+','.join(f'0x{x:02x}' for x in data[i:i+24])+',\n' for i in range(0,len(data),24))
    parts.append(f'}};\nconst lv_image_dsc_t launcher_{name} = {{\n'
                 f' .header = {{.magic=LV_IMAGE_HEADER_MAGIC, .cf=LV_COLOR_FORMAT_RGB565, .w={W}, .h={H}, .stride={W*2}}},\n'
                 f' .data_size=sizeof(pixels_{name}), .data=pixels_{name}\n}};\n')
(OUT/'launcher_art.c').write_text(''.join(parts))
print(f'Generated {len(names)} RGB565 images: {W*H*2*len(names)} Flash bytes')
