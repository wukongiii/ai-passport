#!/usr/bin/env python3
"""Generate the fixed scoreboard font using pinned lv_font_conv 1.5.3."""
import argparse
import hashlib
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
SOURCE_SHA256 = "2c76254f6fc379fddfce0a7e84fb5385bb135d3e399294f6eeb6680d0365b74b"
SOURCE_COMMIT = "f8d157532fbfaeda587e826d4cd5b21a49186f7c"


def codepoints():
    text = "\n".join((ROOT / f).read_text() for f in
                     ("main/score/score_strings.h", "main/ui/app_strings.h", "main/app/app_strings.h", "main/input/text_input_strings.h"))
    strings = re.findall(r'^#define\s+TXT_\w+\s+"([^"]*)"', text, re.M)
    return sorted(set(map(ord, "".join(strings))) | set(range(32, 127)))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=Path, required=True)
    parser.add_argument("--converter", type=Path, required=True)
    args = parser.parse_args()
    if hashlib.sha256(args.font.read_bytes()).hexdigest() != SOURCE_SHA256:
        parser.error("source font SHA-256 mismatch")
    points = codepoints()
    for size in (16, 14):
        destination = ROOT / f"assets/fonts/score_font_{size}.c"
        subprocess.run([str(args.converter.resolve()), "--font", str(args.font.resolve()),
                        "--symbols", "".join(map(chr, points)), "--size", str(size), "--bpp", "4",
                        "--format", "lvgl", "--no-compress", "--no-kerning", "--lv-font-name",
                        f"score_font_{size}", "--lv-include", "lvgl.h", "-o", str(destination)], check=True)
        text = destination.read_text()
        # Strip machine paths from the generated options comment.
        text = re.sub(r"Opts:.*", "Opts: tools/generate_score_font.py (lv_font_conv 1.5.3)", text)
        destination.write_text(text.rstrip() + "\n")
        print(f"Generated {len(points)} glyphs at {size}px; {destination.stat().st_size} source bytes")
    inventory = ROOT / "assets/fonts/score_font_inventory.c"
    inventory.write_text("/* Generated by tools/generate_score_font.py. */\n#include <stdint.h>\n"
                         "const uint32_t score_font_codepoints[] = {\n    " +
                         ", ".join(f"0x{p:04x}" for p in points) + "\n};\n"
                         f"const unsigned score_font_codepoint_count = {len(points)};\n")


if __name__ == "__main__":
    main()
